"""Simple calculator functions for the GBA 6270 CI/CD pipeline."""


def add(a, b):
    """Return the sum of a and b."""
    return a + b


def subtract(a, b):
    """Return a minus b."""
    return a - b


def square(a):
    """Return a squared."""
    return a * a


def cube(a):
    """Return a cubed."""
    return a * a * a